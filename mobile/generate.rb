# Generate native transport names and Swift response models from the canonical OpenAPI file.
require "yaml"
root = File.expand_path("..", __dir__)
spec = YAML.load_file(File.join(root, "backend/api/openapi.yaml"))
models = %w[User Session LinkRequest VerifyRequest Content Catalog Progress SkillProgress AttemptInput Attempt Submission Submissions Document Correction CorrectionError CorrectionProgress Support MockReview MockReviews MockStart MockAnswer MockFinish MockResult MockSession OralStart OralFinish CriterionFeedback OralSession OralSessions SpeechInput Transcript Capability ActiveProvider MemberAccess StoreProduct StoreProducts StoreReceipt StoreOrder StorePurchaseInput StoreOrderInput]
routes = %w[requestLogin verifyLogin logout getMember deleteMember exportMember listCatalog listPractice gradeAttempt getProgress getSubmissions getSubmission getSupport getMemberAccess listCompletedMocks startMock getMock saveMockAnswers finishMock startOral listOral finishOral transcribeOral speakQuestion submitWork downloadDocument getStoreProducts reserveStoreOrder cancelStoreOrder verifyStorePurchase]
operations = spec.fetch("paths").flat_map { |path, methods|
  methods.values.select { |op| routes.include?(op["operationId"]) }.map { |op| [op["operationId"], path] }
}.to_h
def swift_type(field)
  return field["$ref"].split("/").last if field["$ref"]
  return "[#{swift_type(field.fetch("items"))}]" if field["type"] == "array"
  return "[String: #{swift_type(field.fetch("additionalProperties"))}]" if field["type"] == "object"
  {"string"=>"String", "boolean"=>"Bool", "number"=>"Double", "integer"=>"Int"}.fetch(field.fetch("type"))
end
swift = ["// Generated by mobile/generate.rb. Do not edit.", "import Foundation", "", "enum APIPath {"]
routes.each { |op| swift << "    static let #{op} = \"#{operations.fetch(op)}\"" }
swift << "}\n"
models.each do |name|
  model = spec.fetch("components").fetch("schemas").fetch(name)
  swift << "struct #{name}: Codable, Equatable, Sendable {"
  model.fetch("properties").each do |key, field|
    # Persisted snapshots and rolling deployments can predate additive display metadata.
    legacy_optional = { "Content" => %w[videoDescription publicCorrection], "Submission" => %w[correctionProgress] }
    needed = Array(model["required"]).include?(key) && !Array(legacy_optional[name]).include?(key)
    swift << "    var #{key}: #{swift_type(field)}#{needed ? '' : '?'}"
  end
  swift << "}\n"
end
java = ["// Generated by mobile/generate.rb. Do not edit.", "package fr.prepamathscrpe.mobile;", "", "final class ApiPath {", "    private ApiPath() {}"]
routes.each { |op| java << "    static final String #{op} = \"#{operations.fetch(op)}\";" }
java << "}"
files = {"ios/Sources/API.generated.swift"=>swift, "android/app/src/main/java/fr/prepamathscrpe/mobile/ApiPath.java"=>java}
files.each do |path, lines|
  target = File.join(__dir__, path)
  result = lines.join("\n") + "\n"
  if ARGV.include?("--check")
    abort "Native contract drift: #{path}" unless File.exist?(target) && File.read(target) == result
  else
    File.write(target, result)
  end
end
